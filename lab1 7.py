kilometers = float(input("Введите количество километров: "))

meters = kilometers * 1000
centimeters = kilometers * 100000
millimeters = kilometers * 1000000

print("Расстояние в метрах:", meters)
print("Расстояние в сантиметрах:", centimeters)
print("Расстояние в миллиметрах:", millimeters)
